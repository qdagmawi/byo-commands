// Generated launchers carry an opaque command ID only. No prompts, input, or keys enter shell code.
export function launcherContent(
  title: string,
  id: string,
  author: string,
  extension: string,
  scheme = "raycast",
  icon = "command-icons/action.png",
) {
  const safeTitle = Array.from(title, (char) => (char.charCodeAt(0) < 32 ? " " : char))
    .join("")
    .trim();
  const context = encodeURIComponent(JSON.stringify({ commandId: id }));
  const url = `${scheme}://extensions/${encodeURIComponent(author)}/${encodeURIComponent(extension)}/search-ai-command?context=${context}`;
  const safeIcon = icon.replace(/[\r\n]/g, "");
  return `# @raycast.schemaVersion 1\n# @raycast.title ${safeTitle}\n# @raycast.mode silent\n# @raycast.platform windows\n# @raycast.icon ${safeIcon}\n# @raycast.packageName Commands\n# Generated by Commands.\nStart-Process -FilePath '${url.replace(/'/g, "''")}'\n`;
}
